type TipKey = keyof typeof TIP_COPY;

function line(key: string): string {
  if (!Object.prototype.hasOwnProperty.call(TIP_COPY, key)) return '';
  return TIP_COPY[key as TipKey];
}

function attrKey(element: Element, name: string, prefix: string): string {
  const value = element.getAttribute(name);
  if (value == null) return '';
  return line(`${prefix}${value}`);
}

export function tipFor(element: Element): string {
  const marked = element.getAttribute('data-tip');
  if (marked) return line(marked);
  if (element.id) {
    const named = line(element.id);
    if (named) return named;
  }
  const direct = [
    attrKey(element, 'data-steps', 'steps-'),
    attrKey(element, 'data-drum', 'drum-'),
    attrKey(element, 'data-scale', 'scale-'),
    attrKey(element, 'data-chord', 'chord-'),
    attrKey(element, 'data-voice', 'voice-'),
    attrKey(element, 'data-preset', 'preset-'),
    attrKey(element, 'data-duty', 'duty-'),
    attrKey(element, 'data-arp', 'arp-'),
    attrKey(element, 'data-step-duty', 'step-duty-'),
    attrKey(element, 'data-step-arp', 'step-arp-'),
    attrKey(element, 'data-mute', 'mute-'),
    attrKey(element, 'data-solo', 'solo-'),
  ].find((item) => item);
  if (direct) return direct;
  if (element.closest('#channels')) {
    const channel = attrKey(element, 'data-channel', 'channel-');
    if (channel) return channel;
  }
  const knob = element.closest('.knob')?.getAttribute('data-knob');
  if (knob) {
    const text = line(`knob-${knob}`);
    if (text) return text;
  }
  if (element.closest('#pats')) return line('pattern');
  if (element.closest('#lane')) return line('lane');
  if (element.closest('#pcs')) return line('custom-note');
  if (element.closest('#radial')) {
    const label = (element.textContent ?? '').replace(/\s+/g, '').toLowerCase();
    return line(`radial-${label}`);
  }
  const dialog = element.closest('dialog');
  const value = element.getAttribute('value') ?? '';
  if (dialog?.id === 'ask-save') {
    if (value === 'save') return line('ask-save');
    if (value === 'discard') return line('ask-discard');
    if (value === 'cancel') return line('ask-cancel');
  }
  if (dialog?.id === 'ask-delete') {
    if (value === 'delete') return line('ask-delete');
    if (value === 'cancel') return line('ask-cancel');
  }
  if (dialog?.id === 'help') return line('help-close');
  return '';
}
